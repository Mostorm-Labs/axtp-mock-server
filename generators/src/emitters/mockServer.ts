function nodeSmoke(): string {
  return `// Generated by axtp-mock-server generator. Do not edit manually.
import assert from "node:assert/strict";
import { AxtpClient, AxtpServer, MockTransport } from "@axtp/runtime";
import { installAudioMockHandlers } from "./audioHandlers.js";

const client = new AxtpClient({ timeoutMs: 200 });
const server = new AxtpServer();
const clientTransport = new MockTransport();
const serverTransport = new MockTransport();

await client.attachTransport(clientTransport);
await server.attachTransport(serverTransport);
installAudioMockHandlers(server);

function bridge(left: MockTransport, right: MockTransport): void {
  while (true) {
    const chunk = left.tryPopOutgoing();
    if (chunk === undefined) return;
    right.injectIncoming(chunk);
  }
}

const pump = setInterval(async () => {
  bridge(clientTransport, serverTransport);
  await server.poll();
  bridge(serverTransport, clientTransport);
  await client.poll();
}, 0);

try {
  const response = await client.callJson("audio.getAlgorithmConfig", "{}");
  assert.equal(JSON.parse(response).noiseSuppression.enabled, true);
  console.log(response);
} finally {
  clearInterval(pump);
  await client.close();
  await server.close();
}
`;
}

