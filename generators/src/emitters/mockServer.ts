function nodeAudioHandlers(): string {
  return `// Generated by axtp-mock-server generator. Do not edit manually.
import type { AxtpServer, JsonRpcHandler } from "@axtp/runtime";

const defaultConfig = {
  noiseSuppression: { enabled: true, level: 1 },
  echoCancellation: { enabled: true, nlpLevel: 1 }
};

const capabilities = ${JSON.stringify(audioCapabilities, null, 2)};

export class AudioMockState {
  private config = structuredClone(defaultConfig);

  install(server: AxtpServer): void {
    server.onJson("audio.getAlgorithmConfig", this.getAlgorithmConfig);
    server.onJson("audio.getAlgorithmCapabilities", this.getAlgorithmCapabilities);
    server.onJson("audio.setAlgorithmConfig", this.setAlgorithmConfig);
  }

  private readonly getAlgorithmConfig: JsonRpcHandler = async () => JSON.stringify(this.config);

  private readonly getAlgorithmCapabilities: JsonRpcHandler = async () => JSON.stringify(capabilities);

  private readonly setAlgorithmConfig: JsonRpcHandler = async (_context, paramsJson) => {
    try {
      const parsed = paramsJson.length > 0 ? JSON.parse(paramsJson) : {};
      const patch = typeof parsed.config === "object" && parsed.config !== null ? parsed.config : parsed;
      this.mergeConfig(patch);
    } catch {
      // Invalid client JSON keeps the previous mock state and still returns a deterministic response.
    }
    return JSON.stringify({
      applyState: "applied",
      requiresAudioRestart: false,
      config: this.config
    });
  };

  private mergeConfig(patch: unknown): void {
    if (typeof patch !== "object" || patch === null) return;
    for (const [algorithm, value] of Object.entries(patch as Record<string, unknown>)) {
      if (typeof value !== "object" || value === null || Array.isArray(value)) {
        (this.config as Record<string, unknown>)[algorithm] = value;
        continue;
      }
      const current = (this.config as Record<string, unknown>)[algorithm];
      if (typeof current !== "object" || current === null || Array.isArray(current)) {
        (this.config as Record<string, unknown>)[algorithm] = value;
        continue;
      }
      Object.assign(current, value);
    }
  }
}

export function installAudioMockHandlers(server: AxtpServer, state = new AudioMockState()): AudioMockState {
  state.install(server);
  return state;
}
`;
}

