const audioConfig = {
  noiseSuppression: { enabled: true, level: 1 },
  echoCancellation: { enabled: true, nlpLevel: 1 }
};

const audioCapabilities = {
  capability: "audio.algorithm",
  updatePolicy: {
    partialUpdateSupported: true,
    multiAlgorithmUpdateSupported: true,
    atomicUpdateSupported: true
  },
  algorithms: {
    noiseSuppression: {
      supported: true,
      enabled: { type: "boolean", defaultBoolean: true },
      level: { type: "uint8", min: 0, max: 5, step: 1, defaultUInt8: 1 }
    },
    echoCancellation: {
      supported: true,
      enabled: { type: "boolean", defaultBoolean: true },
      nlpLevel: { type: "uint8", min: 0, max: 3, step: 1, defaultUInt8: 1 }
    }
  }
};

export async function emitMockServerFiles(spec: SpecModel, generatedDir: string): Promise<void> {
  await Promise.all([
    emitSharedFixtures(spec, path.join(generatedDir, "shared")),
    emitNodeMockServer(path.join(generatedDir, "node-mock-server")),
    emitCppMockServer(path.join(generatedDir, "cpp-mock-server"))
  ]);
}

async function emitSharedFixtures(spec: SpecModel, dir: string): Promise<void> {
  const audioMethods = spec.methods
    .filter((method) => method.domain === "audio")
    .sort((lhs, rhs) => lhs.id - rhs.id)
    .map((method) => ({
      id: method.id,
      name: method.name,
      requestSchema: method.requestSchema,
      responseSchema: method.responseSchema
    }));
  await Promise.all([
    writeTextFile(path.join(dir, "audio-scenario.json"), toJsonStable({
      name: "audio-default",
      description: "Default AXTP audio mock responses for client-side protocol testing.",
      methods: {
        "audio.getAlgorithmConfig": { response: audioConfig },
        "audio.getAlgorithmCapabilities": { response: audioCapabilities },
        "audio.setAlgorithmConfig": {
          response: {
            applyState: "applied",
            requiresAudioRestart: false,
            config: audioConfig
          }
        }
      }
    })),
    writeTextFile(path.join(dir, "audio-registry.json"), toJsonStable({ methods: audioMethods }))
  ]);
}

